import { describe, expect, it, test } from 'bun:test'

import {
  findOrphanCandidates,
  isExcluded,
  orphanSweepLine,
  referenceNeedles,
  tokensIn,
} from './orphan-sweep'

describe('orphan-sweep exclusion rules', () => {
  it('never considers non-code, vendored, derived or runner-entry files', () => {
    for (const excluded of [
      'assets/logo.png',
      '.agents/skills/x/resources/airtable-design-analysis.json',
      'sdk/vendor/ripgrep/x64-linux/rg',
      'common/src/constants/protocol-bundle.generated.ts',
      'cli/src/utils/__tests__/chat-history.test.ts',
      'cli/src/utils/index.ts',
      'package.json',
      'tsconfig.base.json',
      // FID-2026-1016-013 E: the durable probes home. A probe is invoked by
      // hand and cited from the untracked dev/ records this scan cannot read,
      // so "no mentioner" says nothing about it.
      'scripts/probes/learnings-prefix-probe.ts',
      'scripts/probes/release-gate-isolation-probe.ts',
    ]) {
      expect(isExcluded(excluded)).toBe(true)
    }
  })

  it('considers an ordinary source module', () => {
    expect(isExcluded('cli/src/utils/block-margins.ts')).toBe(false)
  })
})

describe('orphan-sweep reference forms', () => {
  it('offers every trailing segment chain with and without the extension', () => {
    expect(referenceNeedles('cli/src/hooks/use-now.ts').sort()).toEqual(
      [
        'cli/src/hooks/use-now.ts',
        'cli/src/hooks/use-now',
        'cli/src/hooks/use-now.js',
        'src/hooks/use-now.ts',
        'src/hooks/use-now',
        'src/hooks/use-now.js',
        'hooks/use-now.ts',
        'hooks/use-now',
        'hooks/use-now.js',
        'use-now.ts',
        'use-now',
        'use-now.js',
      ].sort(),
    )
  })

  it('splits a scoped import into every trailing segment', () => {
    const tokens = tokensIn(
      "import { x } from '@savant-code/common/util/log-data'\n",
    )
    expect(tokens.has('@savant-code/common/util/log-data')).toBe(true)
    expect(tokens.has('util/log-data')).toBe(true)
    expect(tokens.has('log-data')).toBe(true)
  })

  it('does not treat an unrelated word in prose as a reference', () => {
    // `bigquery.googleapis.com` and `cloud/bigquery-basics` must not satisfy a
    // needle of `bigquery`, or a shared word would mask a real orphan.
    const tokens = tokensIn(
      'see https://bigquery.googleapis.com/v2 and google/cloud/bigquery-basics\n',
    )
    expect(tokens.has('bigquery')).toBe(false)
  })
})

describe('orphan-sweep recurring line (session-end wiring)', () => {
  test('reports counts and the command, never a verdict', () => {
    // Runs the real sweep once against the real tree (FID-2026-1016-013 E).
    // Asserted by SHAPE: a count that changes as the tree is cleaned must not
    // turn this test red, and the line must stay advisory.
    const line = orphanSweepLine()

    expect(line).not.toBeNull()
    expect(line).toMatch(
      /^orphan-sweep: (no candidate among \d+ tracked file\(s\)|\d+ candidate\(s\) among \d+ tracked file\(s\) — ADVISORY)/,
    )
    expect(line).toContain('bun scripts/orphan-sweep.ts')
  })
})

describe('orphan-sweep candidate detection', () => {
  it('does not report a module imported without its extension', () => {
    // Regression: matching only `basename.ts` reported every imported module
    // in the repository (1,339 candidates measured on this tree).
    const files = ['cli/src/hooks/use-now.ts', 'cli/src/app.ts']
    const contents = new Map([
      ['cli/src/hooks/use-now.ts', 'export const useNow = 1\n'],
      ['cli/src/app.ts', "import { useNow } from './hooks/use-now'\n"],
    ])

    const reported = findOrphanCandidates(files, contents).map((c) => c.file)
    // `app.ts` is itself unreferenced in this two-file fixture and is
    // correctly reported; the assertion is about the imported module.
    expect(reported).not.toContain('cli/src/hooks/use-now.ts')
  })

  it('does not report a file cited elsewhere only as a provenance path', () => {
    // Regression: removing the candidate's path from a shared corpus erased
    // the very reference that proved it was used.
    const files = ['cli/scripts/generate-savant-icons.ts', 'cli/src/icons.ts']
    const contents = new Map([
      ['cli/scripts/generate-savant-icons.ts', '// generator\n'],
      [
        'cli/src/icons.ts',
        '// generated by cli/scripts/generate-savant-icons.ts\n',
      ],
    ])

    const reported = findOrphanCandidates(files, contents).map((c) => c.file)
    // The provenance path is a real reference: the generator must not be
    // reported. `icons.ts` has no referencer here and is a true candidate.
    expect(reported).not.toContain('cli/scripts/generate-savant-icons.ts')
  })

  it('does not report a module imported with its emitted .js extension', () => {
    // Defect 3 (FID-2026-1016-013): `scripts/audit-rebrand-corruption.ts` is
    // imported as './audit-rebrand-corruption.js' by the repository gate, and
    // the pre-fix needle set had no `.js` spelling for a `.ts` path.
    const files = [
      'scripts/audit-rebrand-corruption.ts',
      'scripts/validate-repository.ts',
    ]
    const contents = new Map([
      ['scripts/audit-rebrand-corruption.ts', 'export const audit = 1\n'],
      [
        'scripts/validate-repository.ts',
        "import { audit } from './audit-rebrand-corruption.js'\n",
      ],
    ])

    const reported = findOrphanCandidates(files, contents).map((c) => c.file)
    expect(reported).not.toContain('scripts/audit-rebrand-corruption.ts')
  })

  it('does not report a file a config names relative to its own directory', () => {
    // Defect 4: the mention is written from the config's directory
    // (`./src/preload/x.ts`), never from the repository root.
    // The fixture path must NOT exist in the tree: these fixtures are held in
    // the corpus by this test, and `scripts/orphan-sweep.test.ts` is itself a
    // tracked file the real sweep reads — naming a real module here would make
    // the sweep report that module as referenced when nothing else names it.
    const files = ['cli/src/preload/phantom-polyfill.ts', 'cli/bunfig.toml']
    const contents = new Map([
      ['cli/src/preload/phantom-polyfill.ts', 'export const polyfill = 1\n'],
      ['cli/bunfig.toml', 'preload = ["./src/preload/phantom-polyfill.ts"]\n'],
    ])

    const reported = findOrphanCandidates(files, contents).map((c) => c.file)
    expect(reported).not.toContain('cli/src/preload/phantom-polyfill.ts')
  })

  it('reports a file nothing but itself references', () => {
    const files = ['cli/src/utils/block-margins.ts']
    const contents = new Map([
      [
        'cli/src/utils/block-margins.ts',
        '// block-margins\nexport const x = 1\n',
      ],
    ])

    expect(findOrphanCandidates(files, contents)).toEqual([
      {
        file: 'cli/src/utils/block-margins.ts',
        reason: 'only its own content references this path or stem',
      },
    ])
  })
})
