/**
 * Provider catalog parity probe + census regenerator (FID-2026-1006-001 M0).
 *
 * The operator required the provider-visibility fix to be automatic "forever,
 * with zero intervention". The register truth-check (window-coverage-check.ts)
 * detects drift against a Census snapshot — but a static census that no code
 * refreshes would leave the "forever" loop dependent on a human. This probe
 * is the other half: it assembles the FULL live catalog exactly as /model
 * does (`fetchGatewayModels(true)`), measures per-provider row counts, and
 * atomically rewrites the committed census
 * (`common/src/constants/provider-catalog-census.json`) that the check/fix
 * surface consumes. A parity run therefore makes reality the source of the
 * next check — no manual census edit, ever.
 *
 *   - `providers:parity`        report + regenerate the census (the default)
 *   - `providers:parity --check` report-only; never writes (for CI)
 *
 * The probe sends the same authenticated fetches as the product, so a run in
 * an operator context (keys in env / stored) captures the truth the picker
 * will serve. Never logs key material (Law 12); exit 0 on success, 1 when the
 * catalog cannot be assembled (upstream total failure).
 */
import { readFileSync, renameSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

import { MODEL_CATALOGS } from '@savant-code/common/providers/model-catalogs'

import { fetchGatewayModels } from '../cli/src/utils/openrouter-models/gateway'

const ROOT = resolve(import.meta.dir, '..')

export const DEFAULT_CENSUS_PATH =
  'common/src/constants/provider-catalog-census.json'

export type CatalogCensus = {
  generatedAt: string
  probe: string
  notes: string
  rows: Record<string, number>
}

/** Count rows per provider prefix (the same prefix /model groups by). */
export function censusFromCatalog(
  catalog: Array<{ id: string }>,
  generatedAt: string = new Date().toISOString(),
): CatalogCensus {
  const rows: Record<string, number> = {}
  for (const model of catalog) {
    const slash = model.id.indexOf('/')
    if (slash <= 0) continue
    const provider = model.id.slice(0, slash)
    rows[provider] = (rows[provider] ?? 0) + 1
  }
  return {
    generatedAt,
    probe: 'scripts/provider-catalog-parity.ts',
    notes:
      'Generated by the parity probe from the live catalog assembly ' +
      '(fetchGatewayModels(true)). Any provider listed with rows > 0 is a ' +
      'live runtime publisher; the window-coverage check/fix consumes this.',
    rows,
  }
}

/**
 * Providers whose catalog is a checked-in map (`ProviderConfig.catalog.modelsRef`)
 * but which are audited as NOT contributing picker rows yet, each with its
 * reason (FID-2026-1007-005). `chatanywhere` was the defect this check exists
 * for: it was registered, catalogued, window-covered and documented, and the
 * `/model` fan-out never asked for it.
 *
 * The check is two-directional: an entry here that STARTS contributing rows is
 * itself reported, so a stale exception cannot hide a provider that has since
 * been wired.
 */
export const CATALOG_PAIRING_EXCEPTIONS: Record<string, string> = {
  cloudflare:
    'no cli-side builder: the roster is served through the SDK routed path ' +
    '(cli/src/utils/openrouter-models/types.ts names cloudflare as SDK-routed) ' +
    'and the picker would need the account-id credential shape plus window-' +
    'register coverage — its own change, audited here rather than assumed.',
}

/**
 * Pairing issues between the checked-in catalog maps and the assembled picker
 * catalog (FID-2026-1007-005 step 5): every provider whose registry entry
 * declares a `modelsRef` must contribute rows, and every audited exception must
 * still be absent, so the gap cannot reopen silently.
 */
export function catalogPairingIssues(catalog: Array<{ id: string }>): string[] {
  const rows = censusFromCatalog(catalog).rows
  const issues: string[] = []
  for (const provider of Object.keys(MODEL_CATALOGS)) {
    const count = rows[provider] ?? 0
    const exception = CATALOG_PAIRING_EXCEPTIONS[provider]
    if (count === 0 && !exception)
      issues.push(
        `${provider}: declares catalog.modelsRef but contributes 0 picker rows — ` +
          'wire a cli-side builder (the intern/atria precedent) or record an audited exception',
      )
    if (count > 0 && exception)
      issues.push(
        `${provider}: audited as not contributing rows, but now contributes ${count} — ` +
          'remove the stale CATALOG_PAIRING_EXCEPTIONS entry',
      )
  }
  return issues
}

/** Sort rows by provider id for stable diffs. */
export function sortedRows(
  rows: Record<string, number>,
): Record<string, number> {
  const sorted: Record<string, number> = {}
  for (const id of Object.keys(rows).sort()) sorted[id] = rows[id]
  return sorted
}

/** Guarded main — report-only with --check, else regenerate + atomic write. */
async function main(): Promise<void> {
  const checkOnly = process.argv.includes('--check')
  const catalog = await fetchGatewayModels(true)
  if (catalog.length === 0) {
    console.error(
      'Parity probe: catalog assembly returned zero rows — aborting.',
    )
    process.exit(1)
  }
  const census = censusFromCatalog(catalog)
  census.rows = sortedRows(census.rows)

  console.log(`Parity census ${census.generatedAt} — ${catalog.length} rows:`)
  for (const [id, rows] of Object.entries(census.rows)) {
    console.log(`  ${id}: ${rows}`)
  }

  // FID-2026-1007-005 step 5: the census is also the place the registry/catalog
  // pairing is checked, because it is the only surface that measures what the
  // picker actually receives per provider.
  const pairingIssues = catalogPairingIssues(catalog)
  if (pairingIssues.length > 0) {
    console.error('Registry/catalog pairing issues:')
    for (const issue of pairingIssues) console.error(`  - ${issue}`)
  } else {
    console.log(
      'Registry/catalog pairing: every modelsRef provider contributes rows.',
    )
  }

  if (checkOnly) {
    console.log('Parity probe (--check): report only; census not modified.')
    process.exit(pairingIssues.length > 0 ? 1 : 0)
  }

  const path = resolve(ROOT, DEFAULT_CENSUS_PATH)
  const next = JSON.stringify(census, null, 2) + '\n'
  const previous = (() => {
    try {
      return readFileSync(path, 'utf8')
    } catch {
      return undefined
    }
  })()
  const changed = previous !== next

  if (!changed) {
    console.log(`Census unchanged (${DEFAULT_CENSUS_PATH}); nothing to write.`)
    process.exit(0)
  }

  const tmp = `${path}.tmp`
  writeFileSync(tmp, next, 'utf8')
  renameSync(tmp, path)
  console.log(`Census regenerated -> ${DEFAULT_CENSUS_PATH}`)
  console.log(
    'Re-run `bun run window-coverage:check` to reconcile the register.',
  )
  process.exit(pairingIssues.length > 0 ? 1 : 0)
}

// Guarded so the pure helpers stay importable by the declared gate suite.
if (import.meta.main) void main()
