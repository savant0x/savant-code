#!/usr/bin/env bun
// Agent-attribution guard — the SINGLE source of the rule that no coding agent
// may be attributed in this repository (operator directive, 2026-10-14, verbatim:
// "it's 100% forbidden from any coding agent to tag my repo").
//
// Why it exists: GitHub converts `Co-Authored-By:` trailers into contributor
// credit on the repository's contributors page, and a `Generated with …`
// watermark advertises the tool in permanent history. The 2026-08-17 incident
// put 21 unapproved Codebuff trailers into reachable history; removing them
// needed a history rewrite. This module is the rule; the commit-msg hook and CI
// are two enforcement points over it (Law 13 — one truth, no divergent copies).
//
// Usage (fail-closed: anything unexpected exits 2, never 0):
//   bun scripts/attribution-guard.ts --message-file <path>   # commit-msg hook
//   bun scripts/attribution-guard.ts --range <base>..<head>  # pushed/PR range
//   bun scripts/attribution-guard.ts --all                   # every reachable commit

import { spawnSync } from 'child_process'
import { existsSync, readFileSync } from 'fs'

/**
 * Disallowed attribution lines in commit messages.
 *
 * Two families: (1) the known agent identities, and (2) a generic shape — a
 * `Co-Authored-By:` trailer or `Generated with/by …` line that names an agent,
 * bot, assistant or model vendor. Legitimate human co-authors are unaffected
 * (there is one human contributor here, so a human trailer is not expected, but
 * it is never silently blocked).
 *
 * Deliberately fail-closed: a false positive blocks an attribution line (safe,
 * visible, one edit from being tuned), while a false negative rewrites
 * repository history. The operator owns the list; agents never relax it — and
 * the anchoring below is what keeps the rule off *prose about* the rule, which
 * is the failure mode that gets guards like this disabled.
 */
const VENDOR =
  'claude|anthropic|openai|copilot|codex|cursor|windsurf|aider|devin|opencode|cline|continue|tabnine|qwen|deepseek|mistral|llama|grok|gemini'
// A watermark is a line that STARTS with the phrase (optionally after the robot
// emoji) and names the tool immediately: `🤖 Generated with Codebuff`,
// `Generated by OpenAI Codex`, `Generated with an LLM`. Anchoring is what keeps
// this rule off prose — the commit that introduced the guard says
// "…plus 'Generated with/by Codebuff' watermark lines…" mid-sentence, and a
// scanner that flags that teaches everyone to disable it.
const WATERMARK = (names: string) =>
  new RegExp(
    `^\\s*(?:\\u{1F916}\\s*)?generated (?:with|by)\\s+(?:an?\\s+)?(?:${names})\\b`,
    // `u` is required: without it the emoji prefix is a literal `u{1F916}` and
    // the watermark `🤖 Generated with Codebuff` would slip through.
    'iu',
  )

export const AGENT_ATTRIBUTION_PATTERNS: ReadonlyArray<RegExp> = [
  // (1) known identities, in either trailer form
  /co-authored-by:.*(?:codebuff|commandcode|freebuff)/i,
  WATERMARK('codebuff|commandcode|freebuff'),
  // (2) generic agent/bot/assistant/vendor shapes. The self-declaring words
  // (bot/agent/assistant/llm) are matched only INSIDE a trailer, where a human
  // name would never be spelled that way; a watermark line is matched on
  // vendor names plus the unambiguous tokens ai/llm/gpt. `model`, `agent` and
  // `assistant` are deliberately absent from the watermark family: this repo's
  // own prose says "generated by the agent loop", and a guard that blocks
  // legitimate messages gets disabled, which is the worse failure.
  /co-authored-by:.*(?:\[bot\]|\bbot\b|\bagent\b|\bassistant\b|\bllm\b)/i,
  /co-authored-by:.*(?:anthropic|openai|deepmind|copilot|codex|cursor|windsurf|aider|devin|opencode|cline|continue|tabnine|qwen|deepseek|mistral|llama|grok|gemini)/i,
  WATERMARK(VENDOR),
  WATERMARK(`${VENDOR}|ai|llm|gpt`),
]

/**
 * Returns the disallowed attribution lines in a commit message (empty = clean).
 * Prose that merely *discusses* the rule (this file, the CHANGELOG, a FID) is a
 * quotation, not a trailer: the patterns above are anchored on the trailer
 * shapes, so a sentence mentioning an agent never trips them.
 */
export function commitWatermarkLines(message: string): string[] {
  const violations: string[] = []
  for (const rawLine of message.split(/\r?\n/)) {
    const line = rawLine.trim()
    if (!line) continue
    for (const pattern of AGENT_ATTRIBUTION_PATTERNS) {
      if (pattern.test(line)) {
        violations.push(line)
        break
      }
    }
  }
  return violations
}

export type AttributionViolation = { sha: string; lines: string[] }

const RECORD_SEP = '\u001e'
const FIELD_SEP = '\u001f'

function runGit(args: string[]): string {
  const result = spawnSync('git', args, {
    encoding: 'utf8',
    stdio: 'pipe',
    windowsHide: true,
    shell: false,
  })
  if (result.status !== 0) {
    const detail = String(result.stderr ?? '').trim() || 'unknown git error'
    throw new Error(`git ${args[0] ?? ''} failed: ${detail}`)
  }
  return String(result.stdout ?? '')
}

/**
 * Scans every commit message in `revArgs` (one `git log` call — no per-commit
 * spawn) and returns the offending commits. Throws on any git failure so the
 * caller fails closed.
 */
export function scanRevisions(revArgs: string[]): AttributionViolation[] {
  const output = runGit([
    'log',
    `--format=%H${FIELD_SEP}%B${RECORD_SEP}`,
    ...revArgs,
  ])
  const violations: AttributionViolation[] = []
  for (const record of output.split(RECORD_SEP)) {
    const trimmed = record.replace(/^\s+/, '')
    if (!trimmed) continue
    const sep = trimmed.indexOf(FIELD_SEP)
    if (sep < 0) continue
    const sha = trimmed.slice(0, sep).trim()
    const lines = commitWatermarkLines(trimmed.slice(sep + 1))
    if (lines.length > 0) violations.push({ sha, lines })
  }
  return violations
}

/**
 * Repository-gate collector: every reachable commit, in the shape
 * `scripts/validate-repository.ts` aggregates. **Fail-closed**: a git failure
 * becomes an issue (the gate fails) instead of throwing, so an inability to
 * scan can never read as a clean history — and this gate travels with the clone
 * (`bun run validate:repository`), which the local hooks and every optional CI
 * check do not.
 */
export function collectAttributionIssues(): {
  code: string
  message: string
}[] {
  try {
    return scanRevisions(['--all']).map((violation) => ({
      code: 'attribution.agent-trailer',
      message: `${violation.sha.slice(0, 12)}: ${violation.lines.join(' | ')}`,
    }))
  } catch (error) {
    return [
      {
        code: 'attribution.scan-failed',
        message: error instanceof Error ? error.message : String(error),
      },
    ]
  }
}

function report(violations: AttributionViolation[]): void {
  console.error(
    '❌ agent-attribution guard: a coding agent is credited in this repository.',
  )
  console.error(
    '   No coding agent may be attributed — ever, by any layer (operator rule, 2026-10-14).',
  )
  for (const v of violations.slice(0, 20)) {
    // A sha is shortened; a non-sha label (the message-file path) is printed as
    // written, so the heading never renders as a truncated fragment.
    const where = /^[0-9a-f]{7,}$/i.test(v.sha) ? v.sha.slice(0, 12) : v.sha
    console.error(`   ${where}  ${v.lines.join(' | ')}`)
  }
  if (violations.length > 20) {
    console.error(`   … ${violations.length - 20} further commits`)
  }
  console.error(
    '   Remove the trailer/watermark line from the commit message and re-commit.',
  )
}

function main(argv: string[]): number {
  const [flag, value] = argv
  if (flag === '--message-file') {
    if (!value || !existsSync(value)) {
      console.error(
        '❌ agent-attribution guard: no readable commit-message file provided.',
      )
      return 2
    }
    const lines = commitWatermarkLines(readFileSync(value, 'utf8'))
    if (lines.length === 0) return 0
    report([{ sha: '(this commit)', lines }])
    return 1
  }
  if (flag === '--range') {
    if (!value || !value.includes('..')) {
      console.error(
        '❌ agent-attribution guard: --range needs an explicit <base>..<head>.',
      )
      return 2
    }
    const violations = scanRevisions([value])
    if (violations.length === 0) return 0
    report(violations)
    return 1
  }
  if (flag === '--all') {
    const violations = scanRevisions(['--all'])
    if (violations.length === 0) return 0
    report(violations)
    return 1
  }
  console.error(
    '❌ agent-attribution guard: usage: --message-file <path> | --range <base>..<head> | --all',
  )
  return 2
}

// Only run as a CLI; importing the module (tests, pre-push-scan) must not exit.
if (import.meta.main) {
  try {
    process.exit(main(process.argv.slice(2)))
  } catch (error) {
    console.error(
      `❌ agent-attribution guard: scan failed, refusing to pass — ${
        error instanceof Error ? error.message : String(error)
      }`,
    )
    process.exit(2)
  }
}
