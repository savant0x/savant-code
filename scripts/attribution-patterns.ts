/**
 * The vocabulary of the agent-attribution rule — the names and shapes that count
 * as crediting a coding agent (operator directive, 2026-10-14, verbatim: "it's
 * 100% forbidden from any coding agent to tag my repo").
 *
 * This module holds the rule's words and NOTHING else, so the two surfaces that
 * judge with them (`./attribution-guard` for commit messages,
 * `./attribution-document-guard` for the records agents write) cannot drift into
 * two denylists — Law 13, one truth. It was split out when the document surface
 * landed (FID-2026-1016-008) because the combined module crossed the repository's
 * 300-line ceiling; the split follows the `fid-ledger` / `fid-ledger-steps` /
 * `fid-ledger-types` precedent.
 *
 * Fail-closed philosophy: a false positive blocks one attribution line — safe,
 * visible, and one edit from being tuned — while a false negative puts unapproved
 * contributor credit into permanent history. The lists therefore err toward
 * naming an agent, and the anchoring below is what keeps the rule OFF *prose
 * about* the rule, which is the failure mode that gets guards like this disabled.
 */

/**
 * Model vendors and agent harnesses whose name in a trailer or watermark is an
 * attribution. `savant` is deliberately absent everywhere in this file: Savant is
 * this repository's own product and its records may credit it (operator ruling
 * 2026-10-16 — attribution is forbidden "for coding agents that are not savant
 * directly").
 */
const VENDOR =
  'claude|anthropic|openai|copilot|codex|cursor|windsurf|aider|devin|opencode|cline|continue|tabnine|qwen|deepseek|mistral|llama|grok|gemini'

/**
 * A watermark is a line that STARTS with the phrase (optionally after the robot
 * emoji) and names the tool immediately: `🤖 Generated with Codebuff`,
 * `Generated by OpenAI Codex`, `Generated with an LLM`. The anchoring is what
 * keeps this rule off prose — the commit that introduced the guard says
 * "…plus 'Generated with/by Codebuff' watermark lines…" mid-sentence, and a
 * scanner that flags that teaches everyone to disable it.
 */
const WATERMARK = (names: string) =>
  new RegExp(
    `^\\s*(?:\\u{1F916}\\s*)?generated (?:with|by)\\s+(?:an?\\s+)?(?:${names})\\b`,
    // `u` is required: without it the emoji prefix is a literal `u{1F916}` and
    // the watermark `🤖 Generated with Codebuff` would slip through.
    'iu',
  )

/**
 * Disallowed attribution lines in commit messages. Two families: (1) the known
 * agent identities, and (2) a generic shape — a `Co-Authored-By:` trailer or
 * `Generated with/by …` line that names an agent, bot, assistant or model
 * vendor. Legitimate human co-authors are unaffected (there is one human
 * contributor here, so a human trailer is not expected, but it is never silently
 * blocked).
 */
export const AGENT_ATTRIBUTION_PATTERNS: ReadonlyArray<RegExp> = [
  // (1) known identities, in either trailer form
  /co-authored-by:.*(?:codebuff|commandcode|freebuff)/i,
  WATERMARK('codebuff|commandcode|freebuff'),
  // (2) generic agent/bot/assistant/vendor shapes. The self-declaring words
  // (bot/agent/assistant/llm) are matched only INSIDE a trailer, where a human
  // name would never be spelled that way; a watermark line is matched on vendor
  // names plus the unambiguous tokens ai/llm/gpt. `model`, `agent` and
  // `assistant` are deliberately absent from the watermark family: this repo's
  // own prose says "generated by the agent loop", and a guard that blocks
  // legitimate messages gets disabled, which is the worse failure.
  /co-authored-by:.*(?:\[bot\]|\bbot\b|\bagent\b|\bassistant\b|\bllm\b)/i,
  /co-authored-by:.*(?:anthropic|openai|deepmind|copilot|codex|cursor|windsurf|aider|devin|opencode|cline|continue|tabnine|qwen|deepseek|mistral|llama|grok|gemini)/i,
  WATERMARK(VENDOR),
  WATERMARK(`${VENDOR}|ai|llm|gpt`),
]

/**
 * Tier A for document values — foreign coding agents and harness brands.
 * `nova` is included because it is a non-Savant lane whose reports live in
 * `dev/nova/`; model vendors are included because `**Author:** Claude` is the
 * failure the document surface exists for. The operator owns this list: removing
 * a token relaxes the rule, adding one tightens it.
 */
const FOREIGN_AGENT_NAMES =
  'codebuff|commandcode|freebuff|buffy|nova|claude|anthropic|openai|codex|copilot|cursor|windsurf|aider|devin|opencode|cline|continue|tabnine|gemini|grok|qwen|mistral|llama'

/** Tier A: a brand anywhere in a field value, plus the template placeholder. */
export const FOREIGN_AGENT_IN_VALUE = new RegExp(
  `\\b(?:${FOREIGN_AGENT_NAMES})\\b|\\[agent name\\]`,
  'i',
)

/**
 * Model names that are NOT a brand on their own. This repository's own ECHO
 * AUDIT lane is staffed by Savant's `code-reviewer` agent and its records name
 * the lane by the model it ran on (`**Verified By:**
 * code-reviewer-deepseek-flash`) — a routing detail of Savant's own harness, not
 * a foreign agent's credit. In a *provenance* field the same token is a brand
 * (`**Author:** DeepSeek`), so it is judged there.
 */
const HARNESS_MODEL_NAMES = 'deepseek|flash|sonnet|opus|haiku|gpt'

/**
 * Tier B — the words that make a value self-declaring as an agent, plus the
 * harness model names, judged **only inside a provenance field**. They are
 * absent from the Tier-A set because this repository's own records use them for
 * its own machinery: `agent-runtime` is a workspace path, `Verifier agent` is an
 * ECHO role, and "AI-assisted" is ordinary prose. A rule that flags those is a
 * rule people turn off, which is the worse failure.
 */
export const SELF_DECLARING_AGENT_VALUE = new RegExp(
  `\\b(?:agent|bot|assistant|llm|ai|${HARNESS_MODEL_NAMES})\\b`,
  'i',
)

/** Provenance fields answer "who wrote this"; evidence fields answer "what ran". */
export const PROVENANCE_FIELDS = new Set([
  'author',
  'authoring agent',
  'maintainer',
  'owned by',
  'signed by',
  'written by',
  'reported by',
  'contributed by',
])

/**
 * The attribution-field shape: an optionally bulleted bold label with a
 * MANDATORY colon (`**Author:**`, `- **Verified By:**`). The colon is what keeps
 * the rule off `**Authoring lane:**` and `**Authority:**`, which merely start
 * with the same letters and say nothing about who is credited. Only the VALUE is
 * judged, so `**Verified By:** Recorded gate evidence below: …` stays legal.
 */
export const ATTRIBUTION_FIELD =
  /^\s*(?:[-*+>]\s*)?\*\*(Author|Authoring agent|Maintainer|Owned by|Fixed by|Verified by|Signed by|Written by|Reported by|Contributed by)\*{0,2}:\s*(.*)$/i

/**
 * `opencode-go` was Savant's OWN provider catalog id (removed by
 * FID-2026-0916-004, still cited in historical records as the route a run took),
 * not the foreign OpenCode CLI agent that `opencode` means here. Values are
 * judged with Savant's own provider id removed, so a record may say
 * `Savant (MiMo V2.5 / opencode-go)` without being read as crediting a foreign
 * agent.
 */
export const SAVANT_PROVIDER_IDS = /\bopencode-go\b/gi
