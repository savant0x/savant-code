#!/usr/bin/env bun
/**
 * orphan-sweep — advisory report of tracked code files nothing appears to reference.
 *
 * Built for FID-2026-1016-011, where the "is anything here dead?" question had
 * to be answered by hand. This makes that question repeatable.
 *
 * ## What it measures
 *
 * Every tracked text file is tokenised once into path-shaped tokens (`./x/y.ts`,
 * `@savant-code/pkg/y`, `y`). A file is reported as an ORPHAN CANDIDATE when
 * every reference form of it (repo-relative path, extension-less path, basename,
 * basename stem) is mentioned only by the candidate itself.
 *
 * ## Two defects this implementation exists to avoid (both measured on this
 * ## tree, both fixed here — see FID-2026-1016-011)
 *
 * 1. **Extension-sensitive matching.** Code imports omit the extension
 *    (`from './types/tool-name'`), so matching `basename.ts` alone reported
 *    every imported module in the repository — 1,339 candidates.
 * 2. **Self-reference erasure.** Deleting the candidate's path from a shared
 *    corpus also deleted genuine references to it, so a file cited only as a
 *    provenance path (`generated by cli/scripts/generate-savant-icons.ts`)
 *    was reported as unreferenced. Mentions are therefore attributed per file
 *    and the candidate's own file is the only one discounted.
 *
 * ## Why this is ADVISORY and never a gate
 *
 * A name-based index cannot see a reference built at runtime (a path assembled
 * from parts, a glob expanded by a config, a module resolved by convention).
 * Those are real references this scan reports as absent, so being wrong in that
 * direction must never fail a build — an operator reads the output and decides.
 * It always exits 0.
 *
 * Run: `bun scripts/orphan-sweep.ts [--quiet]`
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dir, '..')

/** Extensions whose content can contain a path reference. */
const TEXT_EXTENSIONS = new Set([
  '.ts',
  '.tsx',
  '.js',
  '.jsx',
  '.mjs',
  '.cjs',
  '.json',
  '.md',
  '.yaml',
  '.yml',
  '.toml',
  '.html',
  '.css',
  '.sh',
  '.rs',
  '.py',
])

/**
 * Only CODE files are candidates. Data, prose and image assets are loaded by
 * directory convention here — `.agents/skills/savant-design-systems/resources/*.json`
 * is read by walking the folder, and a preset JSON is legitimately named
 * nowhere (1,657 such "candidates" on the first run). Restricting to code is
 * what makes the output actionable; assets were audited by hand in
 * FID-2026-1016-011 instead.
 */
const CANDIDATE_EXTENSIONS = new Set([
  '.ts',
  '.tsx',
  '.js',
  '.jsx',
  '.mjs',
  '.cjs',
  '.rs',
])

/**
 * Never reported. Each entry is a whole exclusion CLASS, not a suppressed
 * individual finding:
 *
 * - vendored third-party trees and lockfiles are not ours to prune;
 * - `*.generated.*` is derived from tracked inputs;
 * - `*.test.*` files are runner entry points, referenced by glob;
 * - barrel `index.ts` and `package.json` are resolved by convention;
 * - top-level docs/configs are referenced by tooling and humans, not by name.
 */
const EXCLUDED_PATTERNS: readonly RegExp[] = [
  /(^|\/)vendor\//,
  /(^|\/)node_modules\//,
  /\.generated\./,
  /(^|\/)dist\//,
  /^sdk\/test\//,
  /\.test\.(ts|tsx|js)$/,
  /\.spec\.(ts|tsx|js)$/,
  /^bun\.lock$/,
  /(^|\/)index\.ts$/,
  /(^|\/)package\.json$/,
  /(^|\/)tsconfig[^/]*\.json$/,
  /^[^/]+\.(md|json|yaml|yml|toml|js|ts)$/,
  /\.d\.ts$/,
]

/** Generic basenames whose absence proves nothing. */
const GENERIC_BASENAMES = new Set([
  'README.md',
  'index.ts',
  'index.tsx',
  'package.json',
  'tsconfig.json',
  'main.ts',
  'types.ts',
  'constants.ts',
  'utils.ts',
  'setup.ts',
])

export function isExcluded(relative: string): boolean {
  if (!CANDIDATE_EXTENSIONS.has(path.extname(relative).toLowerCase())) {
    return true
  }
  if (EXCLUDED_PATTERNS.some((pattern) => pattern.test(relative))) return true
  return GENERIC_BASENAMES.has(path.basename(relative))
}

/** The forms a reference to `relative` can take, most specific first. */
export function referenceNeedles(relative: string): string[] {
  const stem = (value: string): string => value.replace(/\.[^./]+$/, '')
  return [
    relative,
    stem(relative),
    path.basename(relative),
    stem(path.basename(relative)),
  ]
}

/**
 * Path-shaped tokens a source file can mention. Split on everything that is not
 * part of a path (`@scope/pkg/a-b.ts` stays one token) and unquote, so
 * `from './x/y'` yields `./x/y`.
 */
export function tokensIn(content: string): Set<string> {
  const tokens = new Set<string>()
  for (const raw of content.split(/[^A-Za-z0-9._/@-]+/)) {
    if (raw.length === 0) continue
    tokens.add(raw)
    let value = raw
    if (value.startsWith('./') || value.startsWith('../')) {
      value = value.replace(/^(\.\.?\/)+/, '')
      tokens.add(value)
    }
    // Add every trailing segment chain: `a/b/c` → `b/c` → `c`.
    const segments = value.split('/')
    for (let index = 0; index < segments.length; index++) {
      tokens.add(segments.slice(index).join('/'))
    }
  }
  return tokens
}

export interface OrphanCandidate {
  file: string
  reason: string
}

/**
 * Attribute every mention of a candidate's reference forms to the file that
 * makes it. A candidate is an orphan only when the set of mentioning files is
 * a subset of the candidate itself — which is the fix for defect 2: the
 * candidate's own header comment is discounted, nobody else's mention is.
 */
export function findOrphanCandidates(
  files: readonly string[],
  contents: ReadonlyMap<string, string>,
): OrphanCandidate[] {
  const candidates = files.filter((file) => !isExcluded(file))

  // needle → candidates that answer to it
  const needleOwners = new Map<string, string[]>()
  for (const candidate of candidates) {
    for (const needle of referenceNeedles(candidate)) {
      const owners = needleOwners.get(needle)
      if (owners) owners.push(candidate)
      else needleOwners.set(needle, [candidate])
    }
  }

  // One pass over the corpus: for each mentioning file, record its tokens'
  // hits against the needle set.
  const mentioners = new Map<string, Set<string>>()
  for (const [file, content] of contents) {
    for (const token of tokensIn(content)) {
      const owners = needleOwners.get(token)
      if (owners === undefined) continue
      for (const owner of owners) {
        const seen = mentioners.get(owner)
        if (seen) seen.add(file)
        else mentioners.set(owner, new Set([file]))
      }
    }
  }

  const orphans: OrphanCandidate[] = []
  for (const candidate of candidates) {
    const seen = mentioners.get(candidate)
    if (seen !== undefined && [...seen].some((file) => file !== candidate)) {
      continue
    }
    orphans.push({
      file: candidate,
      reason: 'only its own content references this path or stem',
    })
  }
  return orphans
}

/** Tracked files, or [] when git cannot answer (never throws). */
function trackedFiles(): string[] {
  try {
    return execFileSync('git', ['ls-files'], { cwd: root, encoding: 'utf8' })
      .split('\n')
      .filter((line) => line.length > 0)
  } catch {
    return []
  }
}

/** Read every tracked text file once; unreadable files contribute nothing. */
function readContents(files: readonly string[]): Map<string, string> {
  const contents = new Map<string, string>()
  for (const relative of files) {
    if (!TEXT_EXTENSIONS.has(path.extname(relative).toLowerCase())) continue
    try {
      contents.set(relative, fs.readFileSync(path.join(root, relative), 'utf8'))
    } catch {
      // A tracked file that cannot be read contributes no references.
    }
  }
  return contents
}

if (import.meta.main) {
  const files = trackedFiles()
  if (files.length === 0) {
    console.error('orphan-sweep: git could not list tracked files — no report')
  } else {
    const contents = readContents(files)
    const candidates = findOrphanCandidates(files, contents)
    if (candidates.length === 0) {
      console.log(
        `orphan-sweep: PASS — no candidate among ${files.length} tracked file(s).`,
      )
    } else {
      console.log(
        `orphan-sweep: ${candidates.length} candidate(s) among ${files.length} tracked file(s) — ADVISORY, verify each before deleting:`,
      )
      if (!process.argv.includes('--quiet')) {
        for (const candidate of candidates) {
          console.log(`- ${candidate.file} — ${candidate.reason}`)
        }
      }
    }
    // Advisory by design: a name-based index cannot see runtime-built
    // references, so this never fails a build (see the header).
  }
  process.exitCode = 0
}
