/**
 * Agent-attribution guard — document content (FID-2026-1016-008).
 *
 * The commit-message half of this rule could not see the records themselves: a
 * 2026-10-16 sweep found `**Author:** <agent>` fields and watermark lines inside
 * session summaries, archived FIDs and the third-party channel, invisible to
 * every enforcement point that existed. These fixtures pin the two families the
 * document layer judges, and — with the same weight — the four shapes it must
 * never judge: Savant's own credit, a human credit, prose that discusses the
 * rule, and a colour quotation of the very trailer it blocks.
 *
 * Every "must never" fixture is a real line from this repository, so the rule is
 * pinned against the records it has to coexist with rather than against a
 * sanitised guess.
 */
import { spawnSync } from 'child_process'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'fs'
import os from 'os'
import path from 'path'

import { describe, expect, it } from 'bun:test'

import {
  collectDocumentAttributionIssues,
  documentAttributionLines,
} from '../attribution-guard'

const GUARD = path.join(import.meta.dir, '..', 'attribution-guard.ts')

function withTempRoot(
  build: (root: string) => void,
  run: (root: string) => void,
): void {
  const root = mkdtempSync(path.join(os.tmpdir(), 'attribution-docs-'))
  try {
    build(root)
    run(root)
  } finally {
    rmSync(root, { recursive: true, force: true })
  }
}

function write(root: string, relativePath: string, content: string): void {
  const full = path.join(root, relativePath)
  mkdirSync(path.dirname(full), { recursive: true })
  writeFileSync(full, content)
}

function runGuard(args: string[]) {
  // `process.execPath` (the running bun binary), never a bare `bun`: under the
  // release gate's sanitized spawn environment a PATH-resolved runtime dies with
  // uv_spawn ENOENT (audit.gate-env-parity, v0.0.30 incident).
  return spawnSync(process.execPath, [GUARD, ...args], {
    encoding: 'utf8',
    windowsHide: true,
    shell: false,
  })
}

describe('documentAttributionLines — the credited-agent family', () => {
  it('flags a non-Savant agent named in an attribution field', () => {
    for (const line of [
      '**Author:** Buffy / Savant',
      '- **Author:** Nova (build-order lane)',
      '- **Author:** Spencer + Nova',
      '**Author:** Claude',
      '**Author:** Claude Code',
      '- **Author:** [Agent name]',
      '**Fixed By:** Codex',
      '**Verified By:** Nova — independent third-party ECHO auditor (2026-08-06, PASS 8/8, design phase);',
      '**Verified by:** FreeBuff ECHO protocol read 0-end; FID RED/GREEN/AUDIT double review.',
      '**Maintainer:** an AI assistant',
    ]) {
      expect(documentAttributionLines(line)).toEqual([line.trim()])
    }
  })

  it('judges a harness model name in a provenance field, where the same token is a brand', () => {
    expect(documentAttributionLines('**Author:** DeepSeek')).toHaveLength(1)
    expect(
      documentAttributionLines('**Written by:** an internal LLM'),
    ).toHaveLength(1)
  })

  it('flags a watermark or a trailer in prose', () => {
    for (const line of [
      '🤖 Generated with Codebuff',
      'Generated with an LLM',
      'Generated by OpenAI Codex',
      'Co-Authored-By: Codebuff <noreply@codebuff.com>',
    ]) {
      expect(documentAttributionLines(line)).toHaveLength(1)
    }
  })
})

describe('documentAttributionLines — what must never be judged', () => {
  it('accepts Savant, a human, an empty field and its own ECHO roles', () => {
    for (const line of [
      '**Author:** Savant',
      '- **Author:** Savant (Orchestrator)',
      '**Author:** Savant / Orchestrator',
      '**Author:** Spencer',
      '**Author:** —',
      '**Author:** Orchestrator (hybrid direct write; operator bug report)',
      '- **Verified By:** Savant — independent AUDIT via code-reviewer (clean — no CRITICAL/HIGH/MEDIUM;',
      '- **Verified By:** Recorded gate evidence below: workspace typecheck, ESLint (0 warnings), markdownlint.',
      '- **Verified By:** 4-way typecheck (sdk/common/agent-runtime/cli) clean; SDK',
      '- **Verified By:** Verifier agent (ECHO AUDIT phase)',
      '- **Verified By:** typecheck × 4 (sdk, common, agent-runtime, cli); full suites',
      // Savant's own AUDIT lane, named by the model it ran on:
      '- **Verified By:** code-reviewer-deepseek-flash — independent implementation AUDIT, clean pass (no CRITICAL/HIGH;',
      // Savant's own provider catalog id, cited as the route a run took:
      '**Reported by:** Savant (MiMo V2.5 / opencode-go)',
      // Savant model routing inside evidence prose:
      '**Verified by:** 23 focused provider tests / 63 expectations; the run went through opencode-go/mimo-v2.5.',
    ]) {
      expect(documentAttributionLines(line)).toEqual([])
    }
  })

  it('accepts labels that merely start with the same letters', () => {
    for (const line of [
      '**Authoring lane:** Nova planning lane; the target harness authors and executes the FIDs.',
      '**Authority:** `packages/agent-runtime/src/run-agent-step/post-terminal-breaker.ts`',
      '**Authoritative architecture:** `docs/design/Agent-Steering Teacher Homegrown Architecture.md`',
      '- **Authorization:** IMPLEMENTATION REVIEW ONLY. This verdict authorizes no closure.',
    ]) {
      expect(documentAttributionLines(line)).toEqual([])
    }
  })

  it('never reads prose that discusses the rule as a credit', () => {
    for (const line of [
      'the Codebuff trailer was removed from 21 commits in the 2026-08-17 rewrite',
      'Generated by the agent loop, so the expectedness producer owns the class',
      'rejects agent-attribution trailers and watermarks at the commit boundary',
    ]) {
      expect(documentAttributionLines(line)).toEqual([])
    }
  })

  it('treats a fenced block as a quotation', () => {
    for (const line of [
      '🤖 Generated with Codebuff   (was passing silently)',
      'Co-Authored-By: Codebuff <noreply@codebuff.com>',
      'Generated with Codebuff',
    ]) {
      expect(documentAttributionLines('```text\n' + line + '\n```')).toEqual([])
    }
  })

  it('treats inline code spans as quotations, including a span that wraps a line', () => {
    for (const line of [
      '  `Co-Authored-By: Codebuff <noreply@codebuff.com>` (all authored as',
      '(`co-authored-by:…commandcodobot|commandcode.ai|codebuff` and',
      'rejects agent-attribution trailers (`Co-Authored-By: Codebuff`,',
      '**Verified by:** x4 typecheck gate. Repo-wide grep: 0 stray `@codebuff/`, `CodebuffClient` references.',
    ]) {
      expect(documentAttributionLines(line)).toEqual([])
    }
    // The real record wraps this span across a line break (CommonMark allows
    // it), which a per-line scanner would read as bare `Codebuff` prose.
    expect(
      documentAttributionLines(
        'Stripped with `git filter-branch` (`sed` deleting `Generated with\nCodebuff` lines and `Co-Authored-By: …codebuff` lines).',
      ),
    ).toEqual([])
  })
})

describe('collectDocumentAttributionIssues — the repository gate', () => {
  it('reports nothing on this repository', () => {
    // No argument: the collector resolves the repository from the working
    // directory, because a FID gate runs suites from `scripts/` while the
    // pre-push hook runs from the pushed repo's top level.
    expect(collectDocumentAttributionIssues()).toEqual([])
  })

  it('reports a credited agent with its repository-relative path', () => {
    withTempRoot(
      (root) => {
        write(root, 'docs/README.md', '# Clean\n')
        write(
          root,
          'dev/session-summaries/2026-10-16-example.md',
          '# Summary\n\n**Author:** Buffy / Savant\n\nBody.\n',
        )
      },
      (root) => {
        const issues = collectDocumentAttributionIssues(root)
        expect(issues).toHaveLength(1)
        expect(issues[0]?.code).toBe('attribution.document-agent-credit')
        expect(issues[0]?.message).toContain(
          'dev/session-summaries/2026-10-16-example.md',
        )
        expect(issues[0]?.message).toContain('Buffy')
      },
    )
  })

  it('skips the verbatim-transcript trees but still scans dev/ records', () => {
    withTempRoot(
      (root) => {
        write(root, 'docs/README.md', '# Clean\n')
        write(
          root,
          'dev/scratchpad/archive/transcript.md',
          'Generated with Codebuff\n',
        )
        write(
          root,
          'dev/exports/graph/export.md',
          '🤖 Generated with Codebuff\n',
        )
        write(root, 'dev/nova/outbox/report.md', '**Author:** Nova\n')
      },
      (root) => {
        const issues = collectDocumentAttributionIssues(root)
        expect(issues).toHaveLength(1)
        expect(issues[0]?.message).toContain('dev/nova/outbox/report.md')
      },
    )
  })

  it('fails closed when no governed tree can be found', () => {
    withTempRoot(
      () => {},
      (root) => {
        const issues = collectDocumentAttributionIssues(root)
        expect(issues).toHaveLength(1)
        expect(issues[0]?.code).toBe('attribution.document-scan-failed')
      },
    )
  })
})

describe('attribution-guard --documents — fail-closed CLI', () => {
  it('exits 1 and names the offending record file and line', () => {
    withTempRoot(
      (root) => {
        write(root, 'docs/README.md', '# Clean\n')
        write(
          root,
          'dev/fids/FID-2026-1016-999-example.md',
          '**Author:** Codex\n',
        )
      },
      (root) => {
        const result = runGuard(['--documents', root])
        expect(result.status).toBe(1)
        expect(result.stderr).toContain('No coding agent may be attributed')
        expect(result.stderr).toContain('dev/fids/FID-2026-1016-999-example.md')
      },
    )
  })

  it('exits 0 on a clean tree and 2 when nothing can be scanned', () => {
    withTempRoot(
      (root) => {
        write(root, 'docs/README.md', '# Clean\n')
      },
      (root) => {
        expect(runGuard(['--documents', root]).status).toBe(0)
      },
    )
    withTempRoot(
      () => {},
      (root) => {
        expect(runGuard(['--documents', root]).status).toBe(2)
      },
    )
  })
})
