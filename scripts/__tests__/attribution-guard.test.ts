/**
 * Agent-attribution guard (operator rule, 2026-10-14: "it's 100% forbidden from
 * any coding agent to tag my repo").
 *
 * The negative fixtures below intentionally SPELL a trailer, because proving the
 * guard fails closed requires a watermarked message to exist somewhere. They
 * live in a throwaway temp repository under the OS temp dir, never in this one,
 * and they are commit MESSAGES only — the repo's own history stays clean.
 */
import { spawnSync } from 'child_process'
import { mkdtempSync, rmSync, writeFileSync } from 'fs'
import os from 'os'
import path from 'path'

import { describe, expect, it } from 'bun:test'

import {
  collectAttributionIssues,
  commitWatermarkLines,
} from '../attribution-guard'

const GUARD = path.join(import.meta.dir, '..', 'attribution-guard.ts')

function runGuard(args: string[], cwd?: string) {
  // `process.execPath` (the running bun binary), never a bare `bun`: under the
  // release gate's sanitized spawn environment a PATH-resolved runtime dies
  // with uv_spawn ENOENT (audit.gate-env-parity, v0.0.30 incident).
  return spawnSync(process.execPath, [GUARD, ...args], {
    cwd,
    encoding: 'utf8',
    windowsHide: true,
    shell: false,
  })
}

function git(cwd: string, args: string[]) {
  // core.hooksPath is emptied so the temp fixture never runs this repo's hooks;
  // no --no-verify is used anywhere.
  const result = spawnSync(
    'git',
    [
      '-c',
      'core.hooksPath=',
      '-c',
      'user.email=fixture@example.com',
      '-c',
      'user.name=Fixture',
      ...args,
    ],
    { cwd, encoding: 'utf8', windowsHide: true, shell: false },
  )
  if (result.status !== 0) {
    throw new Error(`git ${args[0]} failed: ${result.stderr}`)
  }
  return String(result.stdout)
}

describe('commitWatermarkLines — the rule itself', () => {
  it('blocks the known agent identities in either form', () => {
    expect(
      commitWatermarkLines(
        'fix: x\n\nCo-Authored-By: Codebuff <noreply@codebuff.com>',
      ),
    ).toHaveLength(1)
    expect(commitWatermarkLines('🤖 Generated with Codebuff')).toHaveLength(1)
    expect(
      commitWatermarkLines(
        'Co-Authored-By: CommandCodeBot <bot@commandcode.ai>',
      ),
    ).toHaveLength(1)
  })

  it('blocks other agent shapes, so the rule is not a two-name denylist', () => {
    for (const line of [
      'Co-Authored-By: Copilot <copilot@github.com>',
      'Co-Authored-By: claude-agent[bot] <noreply@anthropic.com>',
      'Co-Authored-By: Some Assistant <x@example.com>',
      'Generated with Cursor',
      'Generated by OpenAI Codex',
      'Generated with an LLM',
    ]) {
      expect(commitWatermarkLines(line)).toHaveLength(1)
    }
  })

  it('never blocks a human co-author or prose that merely mentions an agent', () => {
    for (const line of [
      'Co-Authored-By: Dana Whitfield <dana@example.com>',
      'fix(hooks): block coding-agent attribution watermarks fail-closed',
      'the Codebuff trailer was removed from 21 commits in the 2026-08-17 rewrite',
      'Generated by the agent loop, so the expectedness producer owns the class',
    ]) {
      expect(commitWatermarkLines(line)).toEqual([])
    }
  })
})

describe('collectAttributionIssues — the repository gate', () => {
  it('reports nothing on this repository (history AND records must be clean)', () => {
    expect(collectAttributionIssues()).toEqual([])
  })

  it('fails closed when the history cannot be scanned at all', () => {
    const previous = process.cwd()
    const notARepo = mkdtempSync(path.join(os.tmpdir(), 'not-a-repo-'))
    try {
      process.chdir(notARepo)
      const issues = collectAttributionIssues()
      expect(issues).toHaveLength(1)
      expect(issues[0]?.code).toBe('attribution.scan-failed')
    } finally {
      process.chdir(previous)
      rmSync(notARepo, { recursive: true, force: true })
    }
  })
})

describe('attribution-guard CLI — fail-closed', () => {
  it('refuses a tagged message file with exit 1 and names the offender', () => {
    const dir = mkdtempSync(path.join(os.tmpdir(), 'attribution-guard-'))
    try {
      const message = path.join(dir, 'COMMIT_EDITMSG')
      writeFileSync(
        message,
        'feat: y\n\nCo-Authored-By: Codebuff <noreply@codebuff.com>\n',
      )
      const result = runGuard(['--message-file', message])
      expect(result.status).toBe(1)
      expect(result.stderr).toContain('No coding agent may be attributed')
      expect(result.stderr).toContain('Codebuff')
      expect(result.stderr).toContain('(this commit)')
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  it('passes a clean message file', () => {
    const dir = mkdtempSync(path.join(os.tmpdir(), 'attribution-guard-'))
    try {
      const message = path.join(dir, 'COMMIT_EDITMSG')
      writeFileSync(
        message,
        'feat: y\n\nCo-Authored-By: Dana Whitfield <dana@example.com>\n',
      )
      expect(runGuard(['--message-file', message]).status).toBe(0)
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  it('exits 2 (never 0) on missing arguments or an unreadable message file', () => {
    expect(runGuard([]).status).toBe(2)
    expect(runGuard(['--range', 'notarange']).status).toBe(2)
    expect(
      runGuard(['--message-file', path.join(os.tmpdir(), 'does-not-exist-xyz')])
        .status,
    ).toBe(2)
  })

  it('catches a watermarked commit inside a pushed range', () => {
    const dir = mkdtempSync(path.join(os.tmpdir(), 'attribution-range-'))
    try {
      git(dir, ['init'])
      writeFileSync(path.join(dir, 'a.txt'), 'a\n')
      git(dir, ['add', '.'])
      git(dir, ['commit', '-m', 'chore: clean commit'])
      const cleanHead = git(dir, ['rev-parse', 'HEAD']).trim()

      writeFileSync(path.join(dir, 'b.txt'), 'b\n')
      git(dir, ['add', '.'])
      git(dir, [
        'commit',
        '-m',
        'feat: tagged\n\nCo-Authored-By: CommandCodeBot <bot@commandcode.ai>',
      ])

      expect(runGuard(['--range', `${cleanHead}..HEAD`], dir).status).toBe(1)
      // An unresolvable revision must never read as clean. A `^`-suffixed range
      // cannot be used here: the Windows spawn layer drops the caret before the
      // guard sees it (measured — the same range through bash correctly exits 2),
      // so the assertion would test the OS, not the guard.
      expect(runGuard(['--range', 'no-such-rev..HEAD'], dir).status).toBe(2)
      expect(
        runGuard(['--range', `${cleanHead}..${cleanHead}`], dir).status,
      ).toBe(0)
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })
})
